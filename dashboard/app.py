# ---------------------------------------------------------------------------
# Cached file readers (cache key includes the file's modification time, so
# re-running a Spark script refreshes the dashboard without a manual clear)
# ---------------------------------------------------------------------------


def file_stamp(path: Path) -> float:
    return path.stat().st_mtime if path.exists() else -1.0


# NOTE: the cache-busting argument must NOT start with an underscore.
# Streamlit deliberately skips underscore-prefixed arguments when building a
# cache key, so a parameter named `_stamp` is ignored and the dashboard keeps
# serving the first version of a file it ever read - even after the Spark
# pipeline has rewritten it.
@st.cache_data(show_spinner=False)
def read_csv(path_str: str, stamp: float) -> pd.DataFrame:
    return pd.read_csv(path_str)


@st.cache_data(show_spinner=False)
def read_json(path_str: str, stamp: float) -> dict:
    return json.loads(Path(path_str).read_text())


def load_csv(path: Path) -> pd.DataFrame | None:
    return read_csv(str(path), file_stamp(path)) if path.exists() else None


def load_json(path: Path) -> dict | None:
    return read_json(str(path), file_stamp(path)) if path.exists() else None


def missing(message: str, command: str) -> None:
    st.warning(message)
    st.code(command, language="bash")


def fmt_int(value) -> str:
    return f"{int(value):,}"


def fmt_money(value) -> str:
    v = float(value)
    if abs(v) >= 1e9:
        return f"{v/1e9:,.2f} B"
    if abs(v) >= 1e6:
        return f"{v/1e6:,.2f} M"
    return f"{v:,.2f}"


